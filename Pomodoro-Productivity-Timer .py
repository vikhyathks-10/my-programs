import time
cycles = int(input("Enter number of cycles: "))

for i in range(cycles):
    print(f"\nCycle {i+1} - Work Time (25 minutes)")
    time.sleep(25 * 60) 
    print("Break Time! (5 minutes)")
    time.sleep(5 * 60)   

print("All cycles completed! ✅")
