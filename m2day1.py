# 1️⃣ Function to print "Hello World"
def hello_world():
    print("Hello World")

hello_world()


# 2️⃣ Function to add two numbers
def add(a, b):
    return a + b

print("Sum:", add(10, 20))


# 3️⃣ Function to check even or odd
def even_odd(num):
    if num % 2 == 0:
        return "Even"
    else:
        return "Odd"

print("Number is:", even_odd(7))


# 4️⃣ Function to find square of a number
def square(num):
    return num * num

print("Square:", square(5))


# 5️⃣ Function to find cube of a number
def cube(num):
    return num * num * num

print("Cube:", cube(3))
